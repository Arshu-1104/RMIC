"""Fetch the frameworks for experiment/head_to_head/ at pinned commits.

    python scripts/fetch_head_to_head_frameworks.py

Clones into the git-ignored data/frameworks/. Needs git; AgentSpec's parser is
regenerated by run_h2h.py with the ANTLR jar bundled in AgentSpec, which needs Java.
Nothing from these repositories is committed here (AgentSpec has no licence file).
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
DEST = REPO / "data" / "frameworks"

PINNED = {
    # name: (url, commit, sparse paths or None)
    "agentspec": ("https://github.com/haoyuwang99/AgentSpec", "e6fa3902e2cfb9681f454b355691b771f70543f8", None),
    "progent": ("https://github.com/sunblaze-ucb/progent", "b02783b896d4bf01a2adf24738015e258db8d35b", None),
    "antlr4": ("https://github.com/antlr/antlr4", "cc82115a4e7f53d71d9d905caa2c2dfa4da58899", ["runtime/Python3/src"]),
    "docstring_parser": ("https://github.com/rr-/docstring_parser", "4815a6957cb36b67cbf1507b64d594c205eb16d6", None),
}


def git(*args: str, cwd: Path | None = None) -> str:
    return subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True, text=True).stdout.strip()


def fetch(name: str, url: str, commit: str, sparse: list[str] | None) -> None:
    path = DEST / name
    if (path / ".git").exists() and git("rev-parse", "HEAD", cwd=path) == commit:
        print(f"{name}: already at {commit[:12]}")
        return
    path.mkdir(parents=True, exist_ok=True)
    git("init", "-q", cwd=path)
    if sparse:
        git("sparse-checkout", "set", *sparse, cwd=path)
    git("fetch", "-q", "--depth", "1", "--filter=blob:none", url, commit, cwd=path)
    git("checkout", "-q", "FETCH_HEAD", cwd=path)
    head = git("rev-parse", "HEAD", cwd=path)
    if head != commit:
        sys.exit(f"{name}: expected {commit}, got {head}")
    print(f"{name}: {commit[:12]}")


def main() -> int:
    for name, (url, commit, sparse) in PINNED.items():
        fetch(name, url, commit, sparse)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
